// Keep current APIs and the frozen v7/v8 migration trees. Only prune unreachable
// root-level historical loaders/snapshots; never infer dead code from filenames alone.
const sourceFiles = codeFiles().filter(file => /\.(?:[cm]?js|tsx?)$/.test(file));
const all = new Set(sourceFiles.map(file => path.resolve(file)));
const dependencies = new Map();
for (const file of sourceFiles) {
  const refs = new Set();
  const visit = node => {
    if (ts.isStringLiteralLike(node) && node.text.startsWith('.')) {
      const raw = path.resolve(path.dirname(file), node.text);
      for (const candidate of [raw, raw.replace(/\.js$/, '.ts'), raw.replace(/\.js$/, '.tsx'), raw + '.ts', path.join(raw, 'index.ts')]) if (all.has(candidate)) refs.add(candidate);
    }
    ts.forEachChild(node, visit);
  };
  visit(parse(file)); dependencies.set(path.resolve(file), refs);
}
const reached = new Set(), queue = sourceFiles.filter(file => !file.startsWith('src/core/')).map(file => path.resolve(file));
while (queue.length) { const file = queue.pop(); if (reached.has(file)) continue; reached.add(file); queue.push(...(dependencies.get(file) ?? [])); }
const historical = /^(?:save-v[2-6]|catalog-v[3-6]|(?:energy|management|save-infrastructure|world-airports)-v6)\.ts$/;
for (const file of walk('src/core').filter(file => path.dirname(file) === 'src/core' && historical.test(path.basename(file)))) {
  if (!reached.has(path.resolve(file))) { report.modules.push({ file, bytes: fs.statSync(file).size }); fs.unlinkSync(file); }
}
assert(report.modules.length > 0, 'Expected some unreachable historical validators');

