// One-off branch maintenance. Removed before this branch is proposed for merge.
const root = process.cwd();
const walk = dir => !fs.existsSync(dir) ? [] : fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
const read = file => fs.readFileSync(file, 'utf8');
const parse = (file, text = read(file)) => ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
const fixtures = walk('tests/fixtures').filter(file => /^v[1-6]-.*\.json$/.test(path.basename(file)));
assert.equal(fixtures.length, 9, 'Review changed legacy fixture inventory before cleanup');
const fixtureNames = new Set(fixtures.map(file => path.basename(file)));
const report = { fixtures, tests: [], modules: [], changedTests: [] };
const isRetiredPath = text => /(?:^|\/)fixtures\/v[1-6]-.*\.json$/.test(text) || fixtureNames.has(path.basename(text)) || /(?:^|\/)src\/core\/save-v[2-6]\.js$/.test(text);
const identifiers = node => {
  const names = new Set();
  const visit = child => { if (ts.isIdentifier(child)) names.add(child.text); ts.forEachChild(child, visit); };
  visit(node); return names;
};
const hasRetiredPath = node => {
  let found = false;
  const visit = child => { if (ts.isStringLiteralLike(child) && isRetiredPath(child.text)) found = true; ts.forEachChild(child, visit); };
  visit(node); return found;
};
const baseName = expr => ts.isIdentifier(expr) ? expr.text : ts.isCallExpression(expr) || ts.isPropertyAccessExpression(expr) || ts.isElementAccessExpression(expr) ? baseName(expr.expression) : '';
const isTest = node => ts.isExpressionStatement(node) && ts.isCallExpression(node.expression) && ['it', 'test'].includes(baseName(node.expression));
const rangesApplied = (text, nodes) => [...new Set(nodes)].sort((a, b) => b.getFullStart() - a.getFullStart()).reduce((current, node) => current.slice(0, node.getFullStart()) + current.slice(node.end), text);

for (const file of walk('tests').filter(file => file.endsWith('.test.ts'))) {
  const original = read(file), source = parse(file, original), removed = [], names = new Set();
  for (const node of source.statements) if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier) && isRetiredPath(node.moduleSpecifier.text)) {
    removed.push(node);
    if (node.importClause) for (const name of identifiers(node.importClause)) names.add(name);
  }
  // Track legacy-only helper declarations before finding their individual test cases.
  let changed = true;
  while (changed) {
    changed = false;
    for (const node of source.statements) {
      if (removed.includes(node) || !(ts.isFunctionDeclaration(node) || ts.isVariableStatement(node))) continue;
      if (!hasRetiredPath(node) && ![...identifiers(node)].some(name => names.has(name))) continue;
      removed.push(node); changed = true;
      if (ts.isFunctionDeclaration(node) && node.name) names.add(node.name.text);
      if (ts.isVariableStatement(node)) for (const declaration of node.declarationList.declarations) for (const name of identifiers(declaration.name)) names.add(name);
    }
  }
  const visit = node => {
    if (isTest(node) && (hasRetiredPath(node) || [...identifiers(node)].some(name => names.has(name)))) {
      removed.push(node);
      report.tests.push({ file, title: node.expression.arguments.find(arg => ts.isStringLiteralLike(arg))?.text ?? node.getText(source).slice(0, 120) });
      return;
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (!removed.length) continue;
  let text = rangesApplied(original, removed);
  text = text.replace("describe('strict current saves and rejected retired flights'", "describe('strict current saves'");
  text = text.replace(/\/\/ Fixture exported from the actual published v4 ordered-route core \(abc4d17\),\r?\n\/\/ not generated by the v5 migration being tested\.\r?\n/, '');
  // Remove now-empty suites, not current business assertions.
  const cleaned = parse(file, text), empty = [];
  const hasTests = node => { let found = false; const scan = child => { if (isTest(child)) found = true; ts.forEachChild(child, scan); }; scan(node); return found; };
  const emptySuites = node => {
    if (ts.isExpressionStatement(node) && ts.isCallExpression(node.expression) && baseName(node.expression) === 'describe' && !hasTests(node)) { empty.push(node); return; }
    ts.forEachChild(node, emptySuites);
  };
  emptySuites(cleaned); text = rangesApplied(text, empty);
  if (!hasTests(parse(file, text))) {
    fs.unlinkSync(file); report.changedTests.push({ file, deleted: true }); continue;
  }
  // Ask the installed TypeScript language service to remove obsolete imports.
  fs.writeFileSync(file, text);
  const absolute = path.resolve(file), options = { target: ts.ScriptTarget.ESNext, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext };
  const host = {
    getScriptFileNames: () => [absolute], getScriptVersion: () => '1',
    getScriptSnapshot: name => fs.existsSync(name) ? ts.ScriptSnapshot.fromString(read(name)) : undefined,
    getCurrentDirectory: () => root, getCompilationSettings: () => options,
    getDefaultLibFileName: value => ts.getDefaultLibFilePath(value), fileExists: ts.sys.fileExists,
    readFile: ts.sys.readFile, readDirectory: ts.sys.readDirectory, directoryExists: ts.sys.directoryExists,
    getDirectories: ts.sys.getDirectories,
  };
  const service = ts.createLanguageService(host);
  const changes = service.organizeImports({ type: 'file', fileName: absolute, skipDestructiveCodeActions: false }, {}, { quotePreference: 'single' });
  for (const change of changes) {
    assert.equal(path.resolve(change.fileName), absolute);
    for (const edit of [...change.textChanges].sort((a, b) => b.span.start - a.span.start)) text = text.slice(0, edit.span.start) + edit.newText + text.slice(edit.span.start + edit.span.length);
  }
  service.dispose(); fs.writeFileSync(file, text);
  report.changedTests.push({ file, deleted: false });
}

