const NOW = Date.parse('2026-09-28T00:00:00Z');
function paidFlightState() {
  const core = new GameCore(NOW);
  const send = (c: Parameters<GameCore['execute']>[0]) => core.execute(c, core.snapshot().lastWallTime);
  send({ type:'found-company', company:{ name:'中华航空', logo:{ kind:'preset', id:'wing' } } });
  send({ type:'tutorial', action:'skip' });
  send({ type:'unlock', airportId:'PVG' });
  send({ type:'buy', modelId:'diamond-da40', airportId:'PEK', passengers:1, cargo:0 });
  const planeId = core.snapshot().fleet[0]!.id;
  send({ type:'load-destination', planeId, to:'PVG' });
  send({ type:'dispatch', planeId, to:'PVG', auto:false });
  core.tick(NOW + core.snapshot().fleet[0]!.flight!.arriveAt * 1000);
  return core.snapshot();
}
async function exportState(page: Page) {
  await page.getByRole('button', {name:'存档设置', exact:true}).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', {name:'导出存档', exact:true}).click();
  const file = await pending;
  const state = validateSave(JSON.parse(await readFile((await file.path())!, 'utf8')));
  await page.getByRole('button', {name:'关闭存档设置', exact:true}).click();
  return state;
}
